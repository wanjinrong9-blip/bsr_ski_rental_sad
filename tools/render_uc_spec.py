"""Render the current UC-01..15 specification into the LaTeX document.

The Markdown specification is the semantic source. Re-run after changing a UC;
do not hand-edit generated requirements.tex and silently diverge from it.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "usecase" / "系统规约.md"
TARGET = ROOT / "output" / "BSR设计需求文档_LaTeX" / "updates" / "requirements.tex"


def tex_escape(value: str) -> str:
    value = value.replace("`", "")
    value = value.replace("**", "")
    mapping = {
        "\\": r"\textbackslash{}",
        "{": r"\{",
        "}": r"\}",
        "$": r"\$",
        "&": r"\&",
        "#": r"\#",
        "_": r"\_",
        "%": r"\%",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(mapping.get(char, char) for char in value)


def fields(paragraph: str) -> list[tuple[str, str]]:
    markers = list(re.finditer(r"\*\*([^*]+)\*\*：", paragraph))
    if not markers:
        return [("说明", paragraph)]
    result: list[tuple[str, str]] = []
    for index, marker in enumerate(markers):
        end = markers[index + 1].start() if index + 1 < len(markers) else len(paragraph)
        result.append((marker.group(1), paragraph[marker.end() : end].strip()))
    return result


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8-sig")
    matches = list(re.finditer(r"(?m)^## UC-(\d{2}) (.+)$", source))
    assert len(matches) == 15, f"expected 15 UCs, found {len(matches)}"
    lines = [
        "% Generated by tools/render_uc_spec.py from usecase/系统规约.md.",
        "% Do not treat local demo status as production approval.",
        r"\subsection{3.2 系统用例规约}",
        r"\noindent 下列十五项规约的语义以现行《系统规约》为准；旧 UC01～UC24 只按映射表迁移。",
    ]
    for index, match in enumerate(matches):
        uc = f"UC-{match.group(1)}"
        title = match.group(2).strip()
        end = matches[index + 1].start() if index + 1 < len(matches) else source.index("\n## 16 状态与费用一致性核对", match.end())
        block = source[match.end() : end].strip()
        paragraphs = [part.strip().replace("\n", " ") for part in re.split(r"\n\s*\n", block) if part.strip()]
        lines.append(rf"\subsubsection{{3.2.{index+1} {tex_escape(uc)} {tex_escape(title)}}}\label{{uc:{match.group(1)}}}")
        lines.append(rf"\begin{{BSRUsecase}}{{{tex_escape(uc)} {tex_escape(title)}}}")
        seen: set[str] = set()
        for paragraph in paragraphs:
            for label, value in fields(paragraph):
                if not value:
                    continue
                lines.append(rf"{tex_escape(label)} & {tex_escape(value)} \\")
                seen.add(label)
        required = {"执行者与利益", "前置", "成功后置", "失败后置", "基本流程", "扩展", "字段/规则", "质量/约束"}
        missing = required - seen
        assert not missing, f"{uc} missing {sorted(missing)}"
        lines.append(r"\end{BSRUsecase}")
        lines.append("")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"rendered {len(matches)} use cases: {TARGET}")


if __name__ == "__main__":
    main()
